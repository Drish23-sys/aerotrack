-- =====================================================================
--  AeroTrack: Aircraft Inspection & Defect Management System
--  PostgreSQL 13+  |  Run with:  psql -d aerotrack -f schema.sql
--  (or:  python init_db.py)
--
--  Contents
--    1. Reset (drops everything this script creates)
--    2. Tables (12, normalised to 3NF) + indexes
--    3. Views (2)
--    4. Trigger functions + triggers (business rules + audit)
--    5. Stored procedures / functions
--    6. Database roles + grants (admin / inspector / viewer)
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- password hashing (crypt / gen_salt)

-- ---------------------------------------------------------------------
-- 1. RESET
-- ---------------------------------------------------------------------
DROP VIEW      IF EXISTS v_open_defects, v_overdue_components CASCADE;
DROP PROCEDURE IF EXISTS sp_start_inspection(INT);
DROP PROCEDURE IF EXISTS sp_close_inspection(INT, TEXT);
DROP PROCEDURE IF EXISTS sp_complete_repair(INT, TEXT, DATE, NUMERIC);
DROP TABLE     IF EXISTS audit_log, app_user, repair, defect, inspection_technician,
                         inspection, technician, inspection_type, component,
                         component_type, aircraft, aircraft_model CASCADE;
DROP FUNCTION  IF EXISTS fn_validate_defect()            CASCADE;
DROP FUNCTION  IF EXISTS fn_ground_on_critical()         CASCADE;
DROP FUNCTION  IF EXISTS fn_repair_sync()                CASCADE;
DROP FUNCTION  IF EXISTS fn_audit()                      CASCADE;
DROP FUNCTION  IF EXISTS fn_try_release_aircraft(INT);
DROP FUNCTION  IF EXISTS fn_login(TEXT, TEXT);

-- ---------------------------------------------------------------------
-- 2. TABLES
-- ---------------------------------------------------------------------

-- Lookup: aircraft models (removes model details from the aircraft table -> 3NF)
CREATE TABLE aircraft_model (
    model_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer   VARCHAR(60) NOT NULL,
    model_name     VARCHAR(60) NOT NULL,
    seat_capacity  INT CHECK (seat_capacity > 0),
    UNIQUE (manufacturer, model_name)
);

CREATE TABLE aircraft (
    aircraft_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_no  VARCHAR(12) NOT NULL UNIQUE,
    model_id         INT NOT NULL REFERENCES aircraft_model(model_id) ON DELETE RESTRICT,
    manufacture_year INT CHECK (manufacture_year BETWEEN 1950 AND 2100),
    status           VARCHAR(12) NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active', 'grounded', 'maintenance'))
);

-- Lookup: component types, each with its required inspection interval
CREATE TABLE component_type (
    type_id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name               VARCHAR(60) NOT NULL UNIQUE,
    inspection_interval_days INT NOT NULL CHECK (inspection_interval_days > 0)
);

CREATE TABLE component (
    component_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aircraft_id         INT NOT NULL REFERENCES aircraft(aircraft_id) ON DELETE RESTRICT,
    type_id             INT NOT NULL REFERENCES component_type(type_id) ON DELETE RESTRICT,
    serial_no           VARCHAR(30) NOT NULL UNIQUE,
    installed_date      DATE NOT NULL DEFAULT CURRENT_DATE,
    last_inspected_date DATE,
    CHECK (last_inspected_date IS NULL OR last_inspected_date >= installed_date)
);

-- Lookup: inspection types (A-Check, C-Check, NDT, Visual ...)
CREATE TABLE inspection_type (
    type_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name   VARCHAR(40) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE technician (
    tech_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(80) NOT NULL,
    certification_level VARCHAR(20) NOT NULL
                        CHECK (certification_level IN ('B1', 'B2', 'C', 'NDT Level 2', 'NDT Level 3')),
    email               VARCHAR(120) UNIQUE,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE inspection (
    inspection_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aircraft_id     INT NOT NULL REFERENCES aircraft(aircraft_id) ON DELETE RESTRICT,
    type_id         INT NOT NULL REFERENCES inspection_type(type_id) ON DELETE RESTRICT,
    inspection_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status          VARCHAR(12) NOT NULL DEFAULT 'scheduled'
                    CHECK (status IN ('scheduled', 'in_progress', 'completed', 'cancelled')),
    remarks         TEXT
);

-- Bridge table for the M:N relationship  TECHNICIAN <-> INSPECTION
CREATE TABLE inspection_technician (
    inspection_id INT NOT NULL REFERENCES inspection(inspection_id) ON DELETE CASCADE,
    tech_id       INT NOT NULL REFERENCES technician(tech_id) ON DELETE RESTRICT,
    role          VARCHAR(20) NOT NULL DEFAULT 'Inspector' CHECK (role IN ('Lead', 'Inspector')),
    PRIMARY KEY (inspection_id, tech_id)
);

CREATE TABLE defect (
    defect_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id INT NOT NULL REFERENCES inspection(inspection_id) ON DELETE RESTRICT,
    component_id  INT NOT NULL REFERENCES component(component_id)  ON DELETE RESTRICT,
    severity      VARCHAR(8) NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    defect_class  VARCHAR(40) NOT NULL,
    description   TEXT NOT NULL,
    status        VARCHAR(10) NOT NULL DEFAULT 'open'
                  CHECK (status IN ('open', 'in_repair', 'resolved')),
    reported_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at   TIMESTAMPTZ,
    CHECK ((status = 'resolved') = (resolved_at IS NOT NULL))
);

CREATE TABLE repair (
    repair_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_id    INT NOT NULL REFERENCES defect(defect_id)   ON DELETE RESTRICT,
    tech_id      INT NOT NULL REFERENCES technician(tech_id) ON DELETE RESTRICT,
    action_taken TEXT NOT NULL,
    cost         NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (cost >= 0),
    start_date   DATE NOT NULL DEFAULT CURRENT_DATE,
    end_date     DATE,
    status       VARCHAR(12) NOT NULL DEFAULT 'in_progress'
                 CHECK (status IN ('in_progress', 'completed', 'failed')),
    CHECK (end_date IS NULL OR end_date >= start_date),
    CHECK ((status = 'in_progress') = (end_date IS NULL))
);

CREATE TABLE app_user (
    user_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(40) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role          VARCHAR(10) NOT NULL CHECK (role IN ('admin', 'inspector', 'viewer')),
    tech_id       INT REFERENCES technician(tech_id) ON DELETE SET NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

-- No foreign keys on purpose: history must survive deletion of the audited row.
CREATE TABLE audit_log (
    log_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    table_name VARCHAR(40) NOT NULL,
    record_id  TEXT NOT NULL,
    action     VARCHAR(6) NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    old_data   JSONB,
    new_data   JSONB,
    changed_by TEXT NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Indexes (foreign keys are not indexed automatically in PostgreSQL)
CREATE INDEX idx_component_aircraft   ON component(aircraft_id);
CREATE INDEX idx_inspection_aircraft  ON inspection(aircraft_id, inspection_date DESC);
CREATE INDEX idx_inspection_status    ON inspection(status);
CREATE INDEX idx_defect_component     ON defect(component_id);
CREATE INDEX idx_defect_inspection    ON defect(inspection_id);
CREATE INDEX idx_defect_unresolved    ON defect(severity) WHERE status <> 'resolved';  -- partial index
CREATE INDEX idx_repair_defect        ON repair(defect_id);
CREATE INDEX idx_repair_tech          ON repair(tech_id);
CREATE INDEX idx_insp_tech_tech       ON inspection_technician(tech_id);
CREATE INDEX idx_audit_record         ON audit_log(table_name, record_id);
CREATE INDEX idx_audit_time           ON audit_log(changed_at DESC);

-- ---------------------------------------------------------------------
-- 3. VIEWS
-- ---------------------------------------------------------------------

-- Every defect that is not yet resolved, most severe first
CREATE VIEW v_open_defects AS
SELECT d.defect_id,
       a.registration_no,
       ct.type_name  AS component,
       c.serial_no,
       d.severity,
       d.defect_class,
       d.status,
       d.reported_at,
       d.inspection_id,
       CASE d.severity WHEN 'CRITICAL' THEN 4 WHEN 'HIGH' THEN 3
                       WHEN 'MEDIUM'   THEN 2 ELSE 1 END AS severity_rank
FROM defect d
JOIN component      c  ON c.component_id = d.component_id
JOIN component_type ct ON ct.type_id     = c.type_id
JOIN aircraft       a  ON a.aircraft_id  = c.aircraft_id
WHERE d.status <> 'resolved'
ORDER BY severity_rank DESC, d.reported_at;

-- Components whose inspection interval has elapsed
-- (never-inspected components count from their installation date)
CREATE VIEW v_overdue_components AS
SELECT c.component_id,
       a.registration_no,
       ct.type_name AS component,
       c.serial_no,
       c.last_inspected_date,
       COALESCE(c.last_inspected_date, c.installed_date) + ct.inspection_interval_days AS due_date,
       CURRENT_DATE - (COALESCE(c.last_inspected_date, c.installed_date)
                       + ct.inspection_interval_days) AS days_overdue
FROM component c
JOIN component_type ct ON ct.type_id    = c.type_id
JOIN aircraft       a  ON a.aircraft_id = c.aircraft_id
WHERE COALESCE(c.last_inspected_date, c.installed_date) + ct.inspection_interval_days < CURRENT_DATE
ORDER BY days_overdue DESC;

-- ---------------------------------------------------------------------
-- 4. TRIGGERS
--    SECURITY DEFINER so the rules still run when a restricted DB role
--    (e.g. role_inspector) performs the original INSERT/UPDATE.
-- ---------------------------------------------------------------------

-- 4a. Data-integrity rule: a defect's component must belong to the inspected
--     aircraft, and defects can only be logged on a live inspection.
CREATE FUNCTION fn_validate_defect() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    v_insp_aircraft INT;
    v_insp_status   TEXT;
    v_comp_aircraft INT;
BEGIN
    SELECT aircraft_id, status INTO v_insp_aircraft, v_insp_status
      FROM inspection WHERE inspection_id = NEW.inspection_id;
    SELECT aircraft_id INTO v_comp_aircraft
      FROM component WHERE component_id = NEW.component_id;

    -- missing parent rows are reported by the foreign-key constraints
    IF v_insp_aircraft IS NULL OR v_comp_aircraft IS NULL THEN
        RETURN NEW;
    END IF;

    IF v_insp_aircraft <> v_comp_aircraft THEN
        RAISE EXCEPTION 'Component % does not belong to the aircraft inspected in inspection %',
                        NEW.component_id, NEW.inspection_id;
    END IF;

    IF TG_OP = 'INSERT' AND v_insp_status NOT IN ('in_progress', 'completed') THEN
        RAISE EXCEPTION 'Defects can only be logged against an in-progress or completed inspection (inspection % is %)',
                        NEW.inspection_id, v_insp_status;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_defect_validate
    BEFORE INSERT OR UPDATE OF inspection_id, component_id ON defect
    FOR EACH ROW EXECUTE FUNCTION fn_validate_defect();

-- 4b. Safety rule: a CRITICAL defect grounds the aircraft immediately.
CREATE FUNCTION fn_ground_on_critical() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
    UPDATE aircraft
       SET status = 'grounded'
     WHERE aircraft_id = (SELECT aircraft_id FROM component WHERE component_id = NEW.component_id)
       AND status <> 'grounded';
    RETURN NULL;
END $$;

CREATE TRIGGER trg_defect_ground
    AFTER INSERT OR UPDATE OF severity ON defect
    FOR EACH ROW WHEN (NEW.severity = 'CRITICAL' AND NEW.status <> 'resolved')
    EXECUTE FUNCTION fn_ground_on_critical();

-- Helper: return an aircraft to service when no unresolved CRITICAL defect remains.
CREATE FUNCTION fn_try_release_aircraft(p_aircraft_id INT) RETURNS BOOLEAN
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
    IF EXISTS (SELECT 1
                 FROM defect d JOIN component c ON c.component_id = d.component_id
                WHERE c.aircraft_id = p_aircraft_id
                  AND d.severity = 'CRITICAL' AND d.status <> 'resolved') THEN
        RETURN FALSE;
    END IF;
    UPDATE aircraft SET status = 'active'
     WHERE aircraft_id = p_aircraft_id AND status = 'grounded';
    RETURN FOUND;
END $$;

-- 4c. Workflow rule: keep defect status in sync with its repairs and
--     release the aircraft once the last critical defect is fixed.
--       repair in_progress -> defect in_repair
--       repair completed   -> defect resolved (+ aircraft released if clear)
--       repair failed      -> defect open again (needs a follow-up repair)
CREATE FUNCTION fn_repair_sync() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    v_aircraft INT;
BEGIN
    IF TG_OP = 'INSERT' AND
       (SELECT status FROM defect WHERE defect_id = NEW.defect_id) = 'resolved' THEN
        RAISE EXCEPTION 'Defect % is already resolved; log a new defect instead', NEW.defect_id;
    END IF;

    IF NEW.status = 'in_progress' THEN
        UPDATE defect SET status = 'in_repair'
         WHERE defect_id = NEW.defect_id AND status = 'open';
    ELSIF NEW.status = 'completed' THEN
        UPDATE defect SET status = 'resolved', resolved_at = now()
         WHERE defect_id = NEW.defect_id;
        SELECT c.aircraft_id INTO v_aircraft
          FROM defect d JOIN component c ON c.component_id = d.component_id
         WHERE d.defect_id = NEW.defect_id;
        PERFORM fn_try_release_aircraft(v_aircraft);
    ELSIF NEW.status = 'failed' THEN
        UPDATE defect SET status = 'open', resolved_at = NULL
         WHERE defect_id = NEW.defect_id;
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_repair_sync
    AFTER INSERT OR UPDATE OF status ON repair
    FOR EACH ROW EXECUTE FUNCTION fn_repair_sync();

-- 4d. Audit trail: one generic function attached to four tables.
--     The application sets  app.current_user  per transaction.
CREATE FUNCTION fn_audit() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    v_pk   TEXT := TG_ARGV[0];
    v_user TEXT := COALESCE(NULLIF(current_setting('app.current_user', true), ''), session_user::text);
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO audit_log (table_name, record_id, action, new_data, changed_by)
        VALUES (TG_TABLE_NAME, to_jsonb(NEW) ->> v_pk, 'INSERT', to_jsonb(NEW), v_user);
    ELSIF TG_OP = 'UPDATE' THEN
        IF to_jsonb(OLD) = to_jsonb(NEW) THEN
            RETURN NULL;                       -- nothing actually changed
        END IF;
        INSERT INTO audit_log (table_name, record_id, action, old_data, new_data, changed_by)
        VALUES (TG_TABLE_NAME, to_jsonb(NEW) ->> v_pk, 'UPDATE', to_jsonb(OLD), to_jsonb(NEW), v_user);
    ELSE
        INSERT INTO audit_log (table_name, record_id, action, old_data, changed_by)
        VALUES (TG_TABLE_NAME, to_jsonb(OLD) ->> v_pk, 'DELETE', to_jsonb(OLD), v_user);
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_audit_aircraft   AFTER INSERT OR UPDATE OR DELETE ON aircraft
    FOR EACH ROW EXECUTE FUNCTION fn_audit('aircraft_id');
CREATE TRIGGER trg_audit_inspection AFTER INSERT OR UPDATE OR DELETE ON inspection
    FOR EACH ROW EXECUTE FUNCTION fn_audit('inspection_id');
CREATE TRIGGER trg_audit_defect     AFTER INSERT OR UPDATE OR DELETE ON defect
    FOR EACH ROW EXECUTE FUNCTION fn_audit('defect_id');
CREATE TRIGGER trg_audit_repair     AFTER INSERT OR UPDATE OR DELETE ON repair
    FOR EACH ROW EXECUTE FUNCTION fn_audit('repair_id');

-- ---------------------------------------------------------------------
-- 5. STORED PROCEDURES / FUNCTIONS
--    Each CALL runs inside the caller's transaction: all-or-nothing.
-- ---------------------------------------------------------------------

CREATE PROCEDURE sp_start_inspection(p_inspection_id INT)
LANGUAGE plpgsql AS $$
DECLARE
    v_status TEXT;
BEGIN
    SELECT status INTO v_status FROM inspection WHERE inspection_id = p_inspection_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Inspection % does not exist', p_inspection_id;
    END IF;
    IF v_status <> 'scheduled' THEN
        RAISE EXCEPTION 'Only a scheduled inspection can be started (inspection % is %)',
                        p_inspection_id, v_status;
    END IF;
    UPDATE inspection SET status = 'in_progress' WHERE inspection_id = p_inspection_id;
END $$;

-- Close an in-progress inspection and stamp the aircraft's components as inspected.
-- (Assumes an inspection covers every component on the aircraft; narrow this
--  by inspection type if your syllabus asks for it.)
-- SECURITY DEFINER: an inspector may close an inspection although role_inspector has no
-- direct UPDATE right on component; the procedure only touches the inspected aircraft.
CREATE PROCEDURE sp_close_inspection(p_inspection_id INT, p_remarks TEXT DEFAULT NULL)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    v_status   TEXT;
    v_aircraft INT;
    v_date     DATE;
BEGIN
    SELECT status, aircraft_id, LEAST(inspection_date, CURRENT_DATE)
      INTO v_status, v_aircraft, v_date
      FROM inspection WHERE inspection_id = p_inspection_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Inspection % does not exist', p_inspection_id;
    END IF;
    IF v_status <> 'in_progress' THEN
        RAISE EXCEPTION 'Only an in-progress inspection can be closed (inspection % is %)',
                        p_inspection_id, v_status;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM inspection_technician WHERE inspection_id = p_inspection_id) THEN
        RAISE EXCEPTION 'Assign at least one technician before closing inspection %', p_inspection_id;
    END IF;

    UPDATE inspection
       SET status = 'completed', remarks = COALESCE(p_remarks, remarks)
     WHERE inspection_id = p_inspection_id;

    UPDATE component
       SET last_inspected_date = v_date
     WHERE aircraft_id = v_aircraft
       AND (last_inspected_date IS NULL OR last_inspected_date < v_date);
END $$;

-- Finish a repair as 'completed' or 'failed'. The trigger trg_repair_sync then
-- resolves / re-opens the defect and releases the aircraft when it is safe.
CREATE PROCEDURE sp_complete_repair(p_repair_id INT,
                                    p_outcome   TEXT,
                                    p_end_date  DATE DEFAULT CURRENT_DATE,
                                    p_cost      NUMERIC DEFAULT NULL)
LANGUAGE plpgsql AS $$
DECLARE
    v_status TEXT;
BEGIN
    IF p_outcome NOT IN ('completed', 'failed') THEN
        RAISE EXCEPTION 'Outcome must be completed or failed, got %', p_outcome;
    END IF;
    SELECT status INTO v_status FROM repair WHERE repair_id = p_repair_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Repair % does not exist', p_repair_id;
    END IF;
    IF v_status <> 'in_progress' THEN
        RAISE EXCEPTION 'Repair % is already %', p_repair_id, v_status;
    END IF;
    UPDATE repair
       SET status = p_outcome, end_date = p_end_date, cost = COALESCE(p_cost, cost)
     WHERE repair_id = p_repair_id;
END $$;

-- Login check used by the Streamlit app (password never leaves the database
-- in clear text; bcrypt hash compared with crypt()).
CREATE FUNCTION fn_login(p_username TEXT, p_password TEXT)
RETURNS TABLE (user_id INT, username VARCHAR, role VARCHAR, tech_id INT)
LANGUAGE sql SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT u.user_id, u.username, u.role, u.tech_id
      FROM app_user u
     WHERE u.username = p_username
       AND u.is_active
       AND u.password_hash = crypt(p_password, u.password_hash);
$$;

-- ---------------------------------------------------------------------
-- 6. DATABASE ROLES + GRANTS  (optional hardening)
--    Roles are cluster-wide, so they are created only if missing.
--    Some managed hosts do not let the app user create roles; in that case
--    this whole block is skipped with a notice and everything else still works.
-- ---------------------------------------------------------------------
DO $roles$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'role_admin')     THEN CREATE ROLE role_admin     NOLOGIN; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'role_inspector') THEN CREATE ROLE role_inspector NOLOGIN; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'role_viewer')    THEN CREATE ROLE role_viewer    NOLOGIN; END IF;

    REVOKE EXECUTE ON PROCEDURE sp_start_inspection(INT), sp_close_inspection(INT, TEXT),
                                sp_complete_repair(INT, TEXT, DATE, NUMERIC) FROM PUBLIC;

    -- viewer: read-only on operational data (no users, no audit log)
    GRANT SELECT ON aircraft_model, aircraft, component_type, component, inspection_type,
                    technician, inspection, inspection_technician, defect, repair,
                    v_open_defects, v_overdue_components
          TO role_viewer;

    -- inspector: viewer + can record inspections, defects and repairs
    GRANT role_viewer TO role_inspector;
    GRANT INSERT, UPDATE ON inspection, inspection_technician, defect, repair TO role_inspector;
    GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO role_inspector;
    GRANT EXECUTE ON PROCEDURE sp_start_inspection(INT),
                               sp_close_inspection(INT, TEXT),
                               sp_complete_repair(INT, TEXT, DATE, NUMERIC)
          TO role_inspector;

    -- admin: everything
    GRANT role_inspector TO role_admin;
    GRANT ALL ON ALL TABLES    IN SCHEMA public TO role_admin;
    GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO role_admin;
EXCEPTION WHEN insufficient_privilege THEN
    RAISE NOTICE 'Skipped database roles: this database user may not create roles or grant privileges.';
END $roles$;
